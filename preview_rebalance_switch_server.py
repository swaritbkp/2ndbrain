"""
Preview a scheme-to-scheme switch (rebalance) for a client without executing it. Runs every compliance check in the same order as the engine workflow — client profile, KYC validity, ELSS lock-in, target-scheme suitability, exit load, and the per-client daily limit — collecting block reasons and safe alternatives. If any check blocks, returns status BLOCKED with reasons, helpful_alternative and the disclaimer, and never requests a confirmation. Otherwise estimates capital-gains tax, checks redemption/purchase cut-off NAV dates, builds the impact and warnings (EXIT_LOAD, SHORT_TERM_GAIN, LTCG_ABOVE_EXEMPTION, AFTER_CUTOFF), then sends a one-time confirmation code out-of-band to the RM console and returns status PREVIEW with impact, warnings, confirmation_id, expires_at, next_step and the disclaimer. The confirmation code itself is never returned or logged, and no execution or verification happens here.

Generated by Synapse (v2 Custom mode). Edit freely — you own this file.
Run:  python preview_rebalance_switch_server.py
"""
from __future__ import annotations

from mcp.server.fastmcp import FastMCP
from decimal import Decimal
from src.rekha.engine.functions import get_client_profile, verify_kyc, check_lockin, check_suitability, compute_exit_load, check_daily_limit, estimate_capital_gains_tax, check_cutoff, request_confirmation
from src.rekha.engine._core import DISCLAIMER, rupees, parse_units
from src.rekha.engine.functions import get_client_profile
from src.rekha.engine.functions import verify_kyc
from src.rekha.engine.functions import check_lockin
from src.rekha.engine.functions import compute_exit_load
from src.rekha.engine.functions import estimate_capital_gains_tax
from src.rekha.engine.functions import check_suitability
from src.rekha.engine.functions import check_daily_limit
from src.rekha.engine.functions import check_cutoff
from src.rekha.engine.functions import request_confirmation
from src.rekha.engine._core import parse_units
from src.rekha.engine._core import rupees
from src.rekha.arena.models import get

mcp = FastMCP("preview_rebalance_switch")


@mcp.tool(name="preview_rebalance_switch", description="Preview a scheme-to-scheme switch (rebalance) for a client without executing it. Runs every compliance check in the same order as the engine workflow — client profile, KYC validity, ELSS lock-in, target-scheme suitability, exit load, and the per-client daily limit — collecting block reasons and safe alternatives. If any check blocks, returns status BLOCKED with reasons, helpful_alternative and the disclaimer, and never requests a confirmation. Otherwise estimates capital-gains tax, checks redemption/purchase cut-off NAV dates, builds the impact and warnings (EXIT_LOAD, SHORT_TERM_GAIN, LTCG_ABOVE_EXEMPTION, AFTER_CUTOFF), then sends a one-time confirmation code out-of-band to the RM console and returns status PREVIEW with impact, warnings, confirmation_id, expires_at, next_step and the disclaimer. The confirmation code itself is never returned or logged, and no execution or verification happens here.")
def preview_rebalance_switch(client_id: str, from_scheme: str, to_scheme: str, units: str) -> dict:
        reasons = []
        helpful_alternative = {}

        profile = get_client_profile(client_id)
        if not profile or profile.get("ok") is False:
            return {
                "status": "BLOCKED",
                "reasons": [profile.get("code") if profile else "CLIENT_NOT_FOUND"],
                "helpful_alternative": {},
                "disclaimer": DISCLAIMER,
            }

        kyc = verify_kyc(client_id)
        if not kyc or kyc.get("kyc_valid") is False:
            reasons.append(kyc.get("block_code") if kyc else "KYC_CHECK_FAILED")
            helpful_alternative["kyc"] = "Complete KYC re-verification before any transaction"

        lockin = check_lockin(client_id, from_scheme, units)
        if not lockin or lockin.get("ok") is False:
            return {
                "status": "BLOCKED",
                "reasons": [lockin.get("code") if lockin else "LOCKIN_CHECK_FAILED"],
                "helpful_alternative": {"units": lockin.get("held_units") if lockin else None},
                "disclaimer": DISCLAIMER,
            }
        if lockin.get("allowed") is False:
            reasons.append(lockin.get("code"))
            unlocked_units = lockin.get("unlocked_units")
            unlocked_dec = parse_units(str(unlocked_units)) if unlocked_units is not None else None
            lockin_alt = {}
            if unlocked_dec is not None and unlocked_dec > 0:
                lockin_alt["switch_units_now"] = unlocked_units
            lockin_alt["next_unlock_date"] = lockin.get("next_unlock_date")
            helpful_alternative["lockin"] = lockin_alt

        suitability = check_suitability(client_id, to_scheme)
        if not suitability or suitability.get("suitable") is False:
            reasons.append(suitability.get("block_code") if suitability else "SUITABILITY_CHECK_FAILED")
            helpful_alternative["suitable_schemes"] = (
                suitability.get("suitable_alternatives") if suitability else []
            )

        load = compute_exit_load(client_id, from_scheme, units)
        if not load or load.get("ok") is False:
            return {
                "status": "BLOCKED",
                "reasons": [load.get("code") if load else "EXIT_LOAD_CHECK_FAILED"],
                "helpful_alternative": {},
                "disclaimer": DISCLAIMER,
            }
        redemption_value_paise = load.get("redemption_value_paise")
        exit_load_paise = load.get("exit_load_paise")

        limit = check_daily_limit(client_id, redemption_value_paise)
        if not limit or limit.get("within_limit") is False:
            reasons.append(limit.get("block_code") if limit else "DAILY_LIMIT_CHECK_FAILED")
            remaining_paise = limit.get("remaining_paise") if limit else None
            helpful_alternative["daily_cap"] = (
                rupees(remaining_paise) if remaining_paise is not None else None
            )

        if reasons:
            return {
                "status": "BLOCKED",
                "reasons": reasons,
                "helpful_alternative": helpful_alternative,
                "disclaimer": DISCLAIMER,
            }

        tax_est = estimate_capital_gains_tax(client_id, from_scheme, units)
        if not tax_est or tax_est.get("ok") is False:
            return {
                "status": "BLOCKED",
                "reasons": [tax_est.get("code") if tax_est else "TAX_ESTIMATE_FAILED"],
                "helpful_alternative": {},
                "disclaimer": DISCLAIMER,
            }

        cutoff_redemption = check_cutoff(from_scheme, "redemption")
        cutoff_purchase = check_cutoff(to_scheme, "purchase")

        short_term_gain_paise = tax_est.get("short_term_gain_paise") or 0
        taxable_ltcg_paise = tax_est.get("taxable_ltcg_paise") or 0
        est_tax_paise = tax_est.get("est_tax_paise") or 0

        impact = {
            "from_scheme": from_scheme,
            "to_scheme": to_scheme,
            "units": units,
            "redemption_value_paise": redemption_value_paise,
            "redemption_value": rupees(redemption_value_paise or 0),
            "exit_load_paise": exit_load_paise,
            "exit_load": rupees(exit_load_paise or 0),
            "short_term_gain_paise": short_term_gain_paise,
            "short_term_gain": rupees(short_term_gain_paise),
            "taxable_ltcg_paise": taxable_ltcg_paise,
            "taxable_ltcg": rupees(taxable_ltcg_paise),
            "est_tax_paise": est_tax_paise,
            "est_tax": rupees(est_tax_paise),
            "assumptions": tax_est.get("assumptions"),
            "redemption_nav_date": cutoff_redemption.get("nav_date") if cutoff_redemption else None,
            "purchase_nav_date": cutoff_purchase.get("nav_date") if cutoff_purchase else None,
        }

        warnings = []
        if exit_load_paise:
            warnings.append({
                "code": "EXIT_LOAD",
                "message": "An exit load of " + rupees(exit_load_paise) + " applies on the switch-out.",
                "amount": rupees(exit_load_paise),
            })
        if short_term_gain_paise:
            warnings.append({
                "code": "SHORT_TERM_GAIN",
                "message": "This switch realises a short-term capital gain of " + rupees(short_term_gain_paise) + ".",
                "amount": rupees(short_term_gain_paise),
            })
        if taxable_ltcg_paise:
            warnings.append({
                "code": "LTCG_ABOVE_EXEMPTION",
                "message": "Taxable long-term capital gain of " + rupees(taxable_ltcg_paise) + " is above the exemption limit.",
                "amount": rupees(taxable_ltcg_paise),
            })
        if (cutoff_redemption and cutoff_redemption.get("after_cutoff")) or (
            cutoff_purchase and cutoff_purchase.get("after_cutoff")
        ):
            warnings.append({
                "code": "AFTER_CUTOFF",
                "message": "The request is after the cut-off time, so the next business day's NAV applies.",
                "redemption_nav_date": cutoff_redemption.get("nav_date") if cutoff_redemption else None,
                "purchase_nav_date": cutoff_purchase.get("nav_date") if cutoff_purchase else None,
            })

        confirmation = request_confirmation(client_id, from_scheme, to_scheme, units)
        if not confirmation or confirmation.get("ok") is False:
            return {
                "status": "BLOCKED",
                "reasons": [confirmation.get("code") if confirmation else "CONFIRMATION_REQUEST_FAILED"],
                "helpful_alternative": {},
                "disclaimer": DISCLAIMER,
            }

        return {
            "status": "PREVIEW",
            "impact": impact,
            "warnings": warnings,
            "confirmation_id": confirmation.get("confirmation_id"),
            "expires_at": confirmation.get("expires_at"),
            "next_step": "Read the one-time code from the RM console and give it to the assistant to execute this switch.",
            "disclaimer": DISCLAIMER,
        }


if __name__ == "__main__":
    mcp.run()
