from __future__ import annotations

from mcp.server.fastmcp import FastMCP
from src.rekha.engine.functions import get_client_profile
from src.rekha.engine.functions import check_lockin
from src.rekha.engine._core import DISCLAIMER
from src.rekha.arena.models import get

mcp = FastMCP("lookup_holdings")


@mcp.tool(name="lookup_holdings", description="Read-only lookup of a client's profile and holdings with ELSS lock-in status. Returns client risk profile, KYC status, and per-scheme lock-in details without modifying any data.")
def lookup_holdings(client_id: str) -> dict:
    profile = get_client_profile(client_id)
    if not profile.get("ok"):
        return {"status": "NOT_FOUND", "code": profile.get("code", "NOT_FOUND")}
    client = profile.get("client", {}) or {}
    holdings_in = profile.get("holdings", []) or []
    holdings_out = []
    for item in holdings_in:
        scheme_code = item.get("scheme_code")
        units = item.get("units")
        lockin = check_lockin(client_id, scheme_code, units)
        holdings_out.append({
            "scheme_code": scheme_code,
            "scheme_name": item.get("scheme_name"),
            "category": item.get("category"),
            "units": units,
            "value_paise": item.get("value_paise"),
            "unlocked_units": lockin.get("unlocked_units"),
            "locked_units": lockin.get("locked_units"),
            "next_unlock_date": lockin.get("next_unlock_date"),
        })
    return {
        "status": "OK",
        "read_only": True,
        "disclaimer": DISCLAIMER,
        "client_id": client_id,
        "risk_profile": client.get("risk_profile"),
        "kyc_status": client.get("kyc_status"),
        "holdings": holdings_out,
    }


if __name__ == "__main__":
    mcp.run()
